// Synchronously run cmd (shell syntax, stderr merged via "2>&1") and return
// the process exit code. Captured stdout+stderr are appended to `out`.
// Returns -1 if the process could not be spawned.
//
// On Windows we explicitly avoid `_popen`: it spawns through cmd.exe with no
// way to suppress the console window, so every invocation flashes a black
// rectangle on screen (very visible on file switch, save, etc.). Instead we
// use CreateProcess + CREATE_NO_WINDOW with an anonymous pipe for stdout.
//
// Declared in editor.h so panel_lync_editor.cpp can call it.
int run_capture(const std::string& cmd, std::string& out) {
    out.clear();
#if defined(_WIN32)
    // Pipe for child stdout (and stderr - we merge them).
    HANDLE rd = nullptr, wr = nullptr;
    SECURITY_ATTRIBUTES sa{};
    sa.nLength = sizeof(sa);
    sa.bInheritHandle = TRUE;
    if (!CreatePipe(&rd, &wr, &sa, 0)) return -1;
    // Read end of the pipe must NOT be inherited by the child, otherwise the
    // pipe stays open after the child exits and ReadFile blocks forever.
    SetHandleInformation(rd, HANDLE_FLAG_INHERIT, 0);

    STARTUPINFOA si{};
    si.cb         = sizeof(si);
    si.dwFlags    = STARTF_USESTDHANDLES;
    si.hStdOutput = wr;
    si.hStdError  = wr;
    si.hStdInput  = GetStdHandle(STD_INPUT_HANDLE);

    PROCESS_INFORMATION pi{};
    // CreateProcessA requires a writable command-line buffer.
    std::vector<char> cmdline(cmd.begin(), cmd.end());
    cmdline.push_back('\0');

    const BOOL ok = CreateProcessA(
        /*lpApplicationName*/ nullptr,
        /*lpCommandLine*/     cmdline.data(),
        /*lpProcessAttributes*/ nullptr,
        /*lpThreadAttributes*/  nullptr,
        /*bInheritHandles*/   TRUE,
        /*dwCreationFlags*/   CREATE_NO_WINDOW,
        /*lpEnvironment*/     nullptr,
        /*lpCurrentDirectory*/nullptr,
        &si, &pi);

    // Parent must close its copy of the write end so ReadFile sees EOF when
    // the child exits.
    CloseHandle(wr);
    if (!ok) {
        const DWORD err = GetLastError();
        char msg[256];
        std::snprintf(msg, sizeof(msg), "run_capture: CreateProcess failed (err=%lu): %s",
                      err, cmdline.data());
        log_write(LogLevel::Error, "editor", msg);
        CloseHandle(rd);
        return -1;
    }

    char buf[512];
    DWORD nread = 0;
    while (ReadFile(rd, buf, (DWORD)sizeof(buf), &nread, nullptr) && nread > 0) {
        out.append(buf, buf + nread);
    }
    CloseHandle(rd);

    WaitForSingleObject(pi.hProcess, INFINITE);
    DWORD code = 0;
    GetExitCodeProcess(pi.hProcess, &code);
    CloseHandle(pi.hProcess);
    CloseHandle(pi.hThread);
    return (int)code;
#else
    FILE* f = ::popen(cmd.c_str(), "r");
    if (!f) return -1;
    char buf[512];
    while (std::fgets(buf, sizeof(buf), f)) out += buf;
    const int status = ::pclose(f);
    return WIFEXITED(status) ? WEXITSTATUS(status) : -1;
#endif
}

