// ---- Lync auto-compile helpers ---------------------------------------------

// Auto-generated manifest filename. Lives in src/ so Lync's `include` (which
// resolves module names against the source file's directory) can find every
// other .lync file alongside it. Marked with a `_zues_` prefix so the
// Source pane can filter it out + so the user knows not to edit it.
inline const char* kZuesManifestName = "_zues_main.lync";

// (Re)generate the auto-include manifest. Scans `src_dir` for every *.lync
// (excluding the manifest itself, hidden `_zues_*` files, and `.__live.lync`
// temp files), then writes:
//
//   // AUTO-GENERATED - do not edit. Regenerated by the editor.
//   include FileA.*
//   include FileB.*
//   ...
//
// `include FileA.*` resolves to `<src_dir>/FileA.lync` because Lync's
// resolve_module_path uses the source file's directory as the base. Returns
// true if the manifest content actually changed (so the watcher can decide
// to recompile). No-op if `src_dir` doesn't exist.
bool regenerate_lync_manifest(const std::filesystem::path& src_dir,
                               const std::filesystem::path& manifest_path) {
    std::error_code ec;
    if (!std::filesystem::exists(src_dir, ec)) return false;

    std::vector<std::string> stems;
    for (const auto& e : std::filesystem::directory_iterator(src_dir, ec)) {
        if (!e.is_regular_file(ec)) continue;
        if (e.path().extension() != ".lync") continue;
        const std::string fn = Engine::editor::path_str(e.path().filename());
        if (fn == kZuesManifestName)              continue;
        if (fn.rfind("_zues_", 0) == 0)           continue;
        if (fn.find(".__live.") != std::string::npos) continue;
        stems.push_back(Engine::editor::path_str(e.path().stem()));
    }
    std::sort(stems.begin(), stems.end());

    std::string body;
    body += "// AUTO-GENERATED - do not edit.\n";
    for (const auto& s : stems) {
        body += "include ";
        body += s;
        body += ".*;\n";        // Lync's parser requires the trailing ';'
    }

    std::string prev;
    if (std::filesystem::exists(manifest_path, ec)) {
        std::ifstream in(manifest_path, std::ios::binary);
        std::ostringstream ss; ss << in.rdbuf();
        prev = ss.str();
    }
    if (prev == body) return false;

    std::ofstream out(manifest_path, std::ios::binary | std::ios::trunc);
    if (!out) return false;
    out.write(body.data(), (std::streamsize)body.size());
    return true;
}

// Walk project_dir recursively; return the maximum last-write-time across
// all .lync files. Returns a zero-initialised time_point if none are found.
std::filesystem::file_time_type scan_lync_mtime(const std::filesystem::path& dir) {
    std::filesystem::file_time_type max_t{};
    std::error_code ec;
    for (const auto& entry : std::filesystem::recursive_directory_iterator(
             dir, std::filesystem::directory_options::skip_permission_denied, ec)) {
        if (entry.path().extension() == ".lync") {
            const auto t = std::filesystem::last_write_time(entry.path(), ec);
            if (!ec && t > max_t) max_t = t;
        }
    }
    return max_t;
}

