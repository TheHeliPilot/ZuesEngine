// Forward decl - implementation below.
std::filesystem::path executable_dir();

// When the project's build.lync_X is empty, fall back to a copy bundled
// next to editor.exe (under <exe_dir>/lync/). This makes packaged builds
// portable: a fresh project doesn't need to hardcode any C:/LyncLang/ path.
// Returns an empty string only when neither the project value nor the
// bundled fallback exists - caller decides what to do.
std::string lync_fallback(const std::string& from_project,
                           const std::filesystem::path& project_base,
                           const char* bundled_filename) {
    if (!from_project.empty()) {
        auto p = std::filesystem::path(from_project);
        return (p.is_absolute() ? p : project_base / p).string();
    }
    std::error_code ec;
    const auto bundled = executable_dir() / "lync" / bundled_filename;
    if (std::filesystem::exists(bundled, ec)) return bundled.string();
    return {};
}

// Build the lync compiler shell invocation from a project's build config.
// Returns an empty string if lync_main is not set.
std::string build_lync_cmd(const Engine::Project& proj) {
    const auto& b    = proj.build;
    const auto  base = std::filesystem::path(proj.project_dir);

    if (b.lync_main.empty()) return {};

    auto resolve = [&](const std::string& s) -> std::string {
        if (s.empty()) return {};
        auto p = std::filesystem::path(s);
        return (p.is_absolute() ? p : base / p).string();
    };

    // Compiler: project setting -> bundled <exe_dir>/lync/lync.exe -> PATH.
    std::string compiler = lync_fallback(b.lync_compiler, base, "lync.exe");
    if (compiler.empty()) compiler = "lync";   // last resort: PATH lookup

    const std::string main_f   = resolve(b.lync_main);
    const std::string plugin_f = lync_fallback(b.lync_plugin,  base, "zues_lync_plugin.dll");
    const std::string incl_f   = lync_fallback(b.lync_include, base, "include");
    const std::string prelude_f= lync_fallback(b.lync_prelude, base, "zues_api.lync");
    const std::string dll_f    = resolve(b.dll_path);

    auto q = [](const std::string& s) { return '"' + s + '"'; };

    std::string cmd = q(compiler) + ' ' + q(main_f) + " --target=dll";
    if (!plugin_f.empty())  cmd += " --plugin=" + q(plugin_f);
    if (!incl_f.empty())    cmd += " --include=" + q(incl_f);
    if (!prelude_f.empty()) cmd += " --prelude=" + q(prelude_f);
    if (!dll_f.empty())     cmd += " -o " + q(dll_f);
    // Always emit the symbol JSON next to the project so the editor can
    // pick it up post-build for type-aware autocomplete + param hints.
    {
        const auto sym_dir = base / ".zues";
        std::error_code ec; std::filesystem::create_directories(sym_dir, ec);
        const auto sym_path = (sym_dir / "symbols.json").string();
        cmd += " --emit-symbols=" + q(sym_path);
    }
    // Hand lync.exe an explicit stdlib path so `using std.math.*;` resolves.
    // Search order: (1) sibling of the lync compiler exe -- the deployed
    // dist layout puts stdlib at `<dist>/lync/stdlib/`; (2) the LyncLang
    // repo's stdlib for dev workflows where lync.exe is built in-tree.
    // First hit wins; if both miss, lync's own fallback (sibling of the
    // exe) takes over and may fail with "module not found" -- the user
    // will see that in the Console.
    {
        std::filesystem::path stdlib_dir;
        std::error_code ec;
        const std::filesystem::path comp_path(compiler);
        if (comp_path.is_absolute() || std::filesystem::exists(comp_path, ec)) {
            const auto sib = comp_path.parent_path() / "stdlib";
            if (std::filesystem::exists(sib, ec)) stdlib_dir = sib;
        }
        if (stdlib_dir.empty()) {
            // Walk up from the compiler dir looking for a LyncLang/stdlib
            // sibling -- typical when running out of a dev build tree.
            std::filesystem::path p = comp_path.parent_path();
            for (int i = 0; i < 6 && !p.empty(); ++i) {
                const auto cand = p / "stdlib";
                if (std::filesystem::exists(cand / "std.math.lync", ec)) {
                    stdlib_dir = cand; break;
                }
                if (p.parent_path() == p) break;
                p = p.parent_path();
            }
        }
        if (!stdlib_dir.empty())
            cmd += " --stdlib=" + q(stdlib_dir.string());
    }
    // run_capture (CreateProcess on Win, popen elsewhere) merges stderr
    // into the captured stdout pipe directly. No `2>&1` redirect, no outer
    // cmd.exe quote wrap — those were artifacts of the old _popen path.
    return cmd;
}

