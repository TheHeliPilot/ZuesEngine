std::filesystem::path executable_dir() {
#if defined(_WIN32)
    char buf[MAX_PATH];
    DWORD n = ::GetModuleFileNameA(nullptr, buf, MAX_PATH);
    if (n == 0 || n == MAX_PATH) return std::filesystem::current_path();
    return std::filesystem::path(buf).parent_path();
#else
    char buf[PATH_MAX];
    ssize_t n = ::readlink("/proc/self/exe", buf, sizeof(buf) - 1);
    if (n <= 0) return std::filesystem::current_path();
    buf[n] = '\0';
    return std::filesystem::path(buf).parent_path();
#endif
}

void logf_info(const char* fmt, ...) {
    char buf[256];
    va_list ap; va_start(ap, fmt);
    std::vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    ZUES_LOG_INFO(buf);
}

void on_window_resized(const WindowResized& e) {
    logf_info("event WindowResized -> %dx%d", e.width, e.height);
}

// Build a small demo world the editor can show and operate on. Real project
// loading lands in Phase 4.2; for now the editor ships with this scene baked
// in so panels have something to render.
void build_demo_world(Engine::ecs::World& world) {
    using namespace Engine::ecs;
    using namespace Engine::components;

    world.register_builtins();
    const ComponentId Position_id   = world.register_component<Position>("Position");
    const ComponentId Velocity_id   = world.register_component<Velocity>("Velocity");
    const ComponentId Tag_Player_id = world.register_component<Tag_Player>("Tag_Player");
    (void)Tag_Player_id;

    auto root = world.create_entity();
    Name root_name{};
    std::snprintf(root_name.value, sizeof(root_name.value), "Scene Root");
    world.add_component(root, world.find_component_id("Name"), &root_name);
    Transform2D rt{};
    rt.position = {640, 360};
    world.add_component(root, world.find_component_id("Transform2D"), &rt);

    Camera2D cam{};
    cam.ortho_size = 10.0f;           // 10 units vertical visible
    cam.sort_mode  = SortMode::YDescending;
    auto cam_e = world.create_entity();
    Name cam_name{};
    std::snprintf(cam_name.value, sizeof(cam_name.value), "Main Camera");
    world.add_component(cam_e, world.find_component_id("Name"), &cam_name);
    world.add_component(cam_e, world.find_component_id("Transform2D"), &rt);
    world.add_component(cam_e, world.find_component_id("Camera2D"), &cam);
    world.set_parent(cam_e, root);

    // A few demo entities to populate the hierarchy + inspector.
    for (int i = 0; i < 4; ++i) {
        auto e = world.create_entity();
        Name n{};
        std::snprintf(n.value, sizeof(n.value), "Box %d", i);
        world.add_component(e, world.find_component_id("Name"), &n);

        Transform2D t{};
        t.position = {200.0f + i * 60.0f, 360.0f};
        t.scale = {1.0f, 1.0f};
        world.add_component(e, world.find_component_id("Transform2D"), &t);

        Position p{static_cast<float>(i) * 10.0f, 0.0f};
        world.add_component(e, Position_id, &p);

        if (i % 2 == 0) {
            Velocity v{1.0f, 0.0f};
            world.add_component(e, Velocity_id, &v);
        }

        world.set_parent(e, root);
    }
}

